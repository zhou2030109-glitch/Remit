def get_reflection_prompt(error_message: str, code: str) -> str:
    """代码执行失败后的自愈指令。

    Args:
        error_message: 执行后端返回的报错详情。
        code: 触发报错的源码。
    """
    return f"""刚刚那次代码执行失败了，报错如下：
{error_message}

请按下述顺序排查并修复，然后务必再次调用函数工具重跑：
1. 语法层面：拼写、括号、缩进
2. 依赖层面：缺少的 import、未安装的库（换一个等价实现）
3. 数据层面：变量名、类型、维度是否对得上
4. 环境层面：文件路径、编码、目录
5. 思路层面：如果同一段代码反复修不好，就拆小步骤、换实现路线或简化模型，不允许原地死磕
6. 全程自主决策，不要反问用户怎么做

出错的代码：
{code}

先简短说明失败原因，再给出修正后的代码（通过函数工具提交）。
"""


